import { cn } from "@/lib/cn";

// Plain <div role="separator"> rather than Base UI's Separator primitive —
// a horizontal/vertical rule needs no interactive behavior from a
// component library (BLUEPRINT §9.4 bundle audit).
function Separator({
  className,
  orientation = "horizontal",
  ...props
}: React.ComponentProps<"div"> & { orientation?: "horizontal" | "vertical" }) {
  return (
    <div
      data-slot="separator"
      role="separator"
      aria-orientation={orientation}
      className={cn(
        "bg-border shrink-0",
        orientation === "horizontal" ? "h-px w-full" : "h-full w-px",
        className,
      )}
      {...props}
    />
  );
}

export { Separator };
